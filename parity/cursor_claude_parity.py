#!/usr/bin/env python3
"""Generate Claude Code config from a Cursor rule set.

One rule set lives in .cursor/. This script writes the Claude Code side:

  .mcp.json                       from .cursor/mcp.json (env-var syntax converted)
  CLAUDE.md (marked block only)   index of the rules
  .claude/rules/*.md              copies of always-on rules, pointers for glob rules
  .claude/agents/*.md             pointers to .cursor/agents/*.md
  .claude/skills/*/SKILL.md       pointers to .cursor/skills/*/SKILL.md
  .claude/settings.json           from .cursor/hooks.json (when present)
  .gitignore                      Claude Code local override lines

Usage:
  python cursor_claude_parity.py <repo-path> [--check] [--config FILE] [options]

Never reads or prints .env values. Standard library only (Python 3.9+).
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

GENERATED_MARKER = "generated by cursor-claude-parity, edit the .cursor source"
PARITY_START = "<!-- claude-parity:start -->"
PARITY_END = "<!-- claude-parity:end -->"
DEFAULT_CONFIG_NAME = ".cursor-claude-parity.json"

CLAUDE_MODEL_ALIASES = frozenset({"sonnet", "opus", "haiku", "inherit"})
CURSOR_HOOK_TO_CLAUDE = {
    "sessionstart": "SessionStart",
    "sessionend": "SessionEnd",
    "pretooluse": "PreToolUse",
    "posttooluse": "PostToolUse",
}
AGENT_SKIP_NAMES = frozenset({"readme"})


@dataclass
class Config:
    """Everything that varies between repos. All optional."""

    # Default value for an env var when the MCP config references ${env:NAME}.
    # Only for public, non-secret values. Becomes ${NAME:-default}.
    env_defaults: dict[str, str] = field(default_factory=dict)
    # If set, agent pointers get this sentence prefixed to their description
    # (for example "Owned by Cursor: do not launch from Claude Code unprompted.").
    lane_note: str = ""
    # Agents whose file name starts with one of these are shared: no lane note.
    shared_agent_prefixes: list[str] = field(default_factory=list)
    # Hook commands containing one of these get "--claude" appended.
    claude_flag_hooks: list[str] = field(default_factory=list)
    # Cursor hook commands containing one of these are not ported.
    skip_hooks: list[str] = field(default_factory=list)
    # Extra PreToolUse matchers: [{"contains": "my-hook.cjs", "matcher": "Edit|Write"}]
    hook_matchers: list[dict[str, str]] = field(default_factory=list)
    # Path (relative to the repo) of a CLAUDE.md template. Optional.
    claude_template: str = ""
    # Lines ensured in .gitignore.
    gitignore_lines: list[str] = field(
        default_factory=lambda: [".claude/settings.local.json", "CLAUDE.local.md"]
    )


@dataclass
class SyncResult:
    conflicts: list[str] = field(default_factory=list)
    drift: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)
    envfile_dropped: list[str] = field(default_factory=list)


def load_config(root: Path, explicit: str | None) -> Config:
    path = Path(explicit) if explicit else root / DEFAULT_CONFIG_NAME
    cfg = Config()
    if not path.is_file():
        if explicit:
            sys.stderr.write(f"Config not found: {path}\n")
            sys.exit(2)
        return cfg
    data = json.loads(read_text(path))
    for key, value in data.items():
        if key.startswith("//"):
            continue
        if not hasattr(cfg, key):
            sys.stderr.write(f"Unknown config key {key!r} in {path}\n")
            sys.exit(2)
        setattr(cfg, key, value)
    return cfg


def repo_root(arg: str) -> Path:
    root = Path(arg).resolve()
    if not root.is_dir():
        sys.stderr.write(f"Not a directory: {root}\n")
        sys.exit(2)
    return root


def read_text(path: Path) -> str:
    # utf-8-sig strips a leading BOM so frontmatter still starts with ---
    return path.read_text(encoding="utf-8-sig")


def is_generated(content: str) -> bool:
    return GENERATED_MARKER in content


def write_or_check(
    path: Path, content: str, check: bool, result: SyncResult, root: Path
) -> None:
    normalized = content if content.endswith("\n") else content + "\n"
    rel = path.relative_to(root) if path.is_relative_to(root) else path
    if not path.is_file():
        if check:
            result.drift.append(f"missing {rel}")
            return
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(normalized, encoding="utf-8")
        return
    existing = read_text(path)
    if existing == normalized:
        return
    if is_generated(existing):
        if check:
            result.drift.append(f"drift {rel}")
            return
        path.write_text(normalized, encoding="utf-8")
        return
    if check:
        result.drift.append(f"drift (not generated) {rel}")
    else:
        result.conflicts.append(
            f"{rel}: exists without the generated marker; not overwritten"
        )


# ---------------------------------------------------------------- MCP


def convert_mcp_string(value: str, cfg: Config) -> str:
    def env_ref(match: re.Match[str]) -> str:
        var = match.group(1)
        default = cfg.env_defaults.get(var)
        return f"${{{var}:-{default}}}" if default else f"${{{var}}}"

    out = re.sub(r"\$\{env:([^}]+)\}", env_ref, value)
    out = out.replace("${userHome}", "${HOME}")
    out = out.replace("${workspaceFolder}/", "")
    out = out.replace("${workspaceFolder}", "${CLAUDE_PROJECT_DIR:-.}")
    return out


def walk_convert(obj: Any, cfg: Config) -> Any:
    if isinstance(obj, str):
        return convert_mcp_string(obj, cfg)
    if isinstance(obj, list):
        return [walk_convert(x, cfg) for x in obj]
    if isinstance(obj, dict):
        return {k: walk_convert(v, cfg) for k, v in obj.items()}
    return obj


def is_sse_url(url: str) -> bool:
    return "/sse" in url.lower()


def convert_mcp_server(
    name: str, server: dict[str, Any], result: SyncResult, cfg: Config
) -> dict[str, Any]:
    server = dict(server)
    if "envFile" in server:
        result.envfile_dropped.append(name)
        del server["envFile"]
    server = walk_convert(server, cfg)
    # `<your-token>` placeholders never work; read the same-named env var instead.
    for block in ("env", "headers"):
        vals = server.get(block)
        if isinstance(vals, dict):
            for key, val in vals.items():
                if isinstance(val, str) and re.fullmatch(r"<[^<>]+>", val.strip()):
                    vals[key] = f"${{{key}}}"
    if "url" in server and "command" not in server:
        if server.get("type") == "streamable-http":
            server["type"] = "http"
        if "type" not in server:
            server["type"] = "sse" if is_sse_url(server["url"]) else "http"
        elif server["type"] == "sse" and server["url"].rstrip("/").endswith("/mcp"):
            # Cursor tolerates "sse" on a streamable HTTP /mcp endpoint; Claude Code does not.
            server["type"] = "http"
    if "command" in server and "args" not in server:
        cmd = server["command"]
        if isinstance(cmd, str) and (
            cmd.endswith((".sh", ".bash")) or ("/" in cmd and not cmd.startswith("node"))
        ):
            server["command"] = "bash"
            server["args"] = [cmd]
    return server


def build_mcp_json(root: Path, result: SyncResult, cfg: Config) -> str | None:
    src = root / ".cursor" / "mcp.json"
    if not src.is_file():
        result.notes.append("no .cursor/mcp.json; .mcp.json not written")
        return None
    data = json.loads(read_text(src))
    servers_out: dict[str, Any] = {}
    for name, server in (data.get("mcpServers") or {}).items():
        servers_out[name] = (
            convert_mcp_server(name, server, result, cfg)
            if isinstance(server, dict)
            else server
        )
    out: dict[str, Any] = {}
    comments = sorted(k for k in data if k.startswith("//"))
    for key in comments:
        out[key] = data[key] if isinstance(data[key], str) else str(data[key])
    if comments:
        out["//generated"] = GENERATED_MARKER
    else:
        out["//"] = f"Claude Code MCP config (from .cursor/mcp.json). {GENERATED_MARKER}"
    out["mcpServers"] = servers_out
    return json.dumps(out, indent=2) + "\n"


# ---------------------------------------------------------------- frontmatter


def parse_simple_frontmatter(text: str) -> tuple[dict[str, str], str] | None:
    if not text.startswith("---"):
        return None
    parts = text.split("---", 2)
    if len(parts) < 3:
        return None
    fm: dict[str, str] = {}
    key: str | None = None
    buf: list[str] = []
    for line in parts[1].splitlines():
        m = re.match(r"^([A-Za-z0-9_-]+):\s*(.*)$", line)
        if m and not line.startswith(" "):
            if key is not None:
                fm[key] = "\n".join(buf).strip()
            key = m.group(1)
            rest = m.group(2).strip()
            if re.fullmatch(r"[>|][+-]?", rest):  # YAML block scalar
                buf = []
            else:
                buf = [rest.strip('"').strip("'")] if rest else []
        elif key is not None and line.startswith(" "):
            buf.append(line.strip())
    if key is not None:
        fm[key] = "\n".join(buf).strip()
    return fm, parts[2]


def extract_frontmatter_lines(text: str) -> list[str]:
    if not text.startswith("---"):
        return []
    parts = text.split("---", 2)
    return parts[1].splitlines() if len(parts) >= 3 else []


def sanitize_prose(text: str) -> str:
    """Generated text avoids em and en dashes."""
    return text.replace("\u2014", "-").replace("\u2013", "-")


def yaml_description_lines(desc: str) -> list[str]:
    text = sanitize_prose(desc.strip())
    if not text:
        return []
    if "\n" in text:
        out = ["description: >-"]
        out.extend(f"  {p}" if p.strip() else "" for p in text.splitlines())
        while out and out[-1] == "":
            out.pop()
        return out
    if any(c in text for c in (":", "#", '"', "'")) or text.startswith(
        ("-", "?", "[", "{", "*", "&", "!", "|", ">", "%", "@", "`")
    ):
        escaped = text.replace("\\", "\\\\").replace('"', '\\"')
        return [f'description: "{escaped}"']
    return [f"description: {text}"]


# ---------------------------------------------------------------- rules


def parse_rule_file(path: Path) -> dict[str, Any]:
    fm, _ = parse_simple_frontmatter(read_text(path)) or ({}, "")
    name = path.parent.name if path.name.upper() == "RULE.MD" else path.stem
    return {
        "name": name,
        "path": path,
        "always_apply": str(fm.get("alwaysApply", "")).lower() == "true",
        "globs": fm.get("globs", "").strip(),
        "description": sanitize_prose(fm.get("description", "").strip()),
    }


def collect_cursor_rules(rules_dir: Path) -> list[dict[str, Any]]:
    """Flat *.mdc plus nested */RULE.md (Cursor project rules layout)."""
    if not rules_dir.is_dir():
        return []
    paths = sorted(rules_dir.glob("*.mdc")) + sorted(rules_dir.glob("*/RULE.md"))
    return [parse_rule_file(p) for p in paths]


def is_mdc(rule: dict[str, Any]) -> bool:
    return rule["path"].suffix == ".mdc"


def build_glob_rule(rule: dict[str, Any], root: Path) -> str:
    rel = rule["path"].relative_to(root)
    globs = []
    for part in re.split(r"[,\n]", rule["globs"]):
        g = part.strip()
        if g.startswith("- "):
            g = g[2:]
        g = g.strip().strip('"').strip("'").strip()
        if g:
            globs.append(g)
    lines = [
        "---",
        "paths:",
        *[f'  - "{g}"' for g in globs],
        "---",
        "",
        f"Read and follow `{rel}` (canonical).",
        "",
        f"<!-- {GENERATED_MARKER} -->",
    ]
    return "\n".join(lines) + "\n"


def build_always_rule_copy(rule: dict[str, Any], root: Path) -> str:
    # Claude Code only inlines `@` imports of .md files, so an imported .mdc never
    # reaches the model. Always-on .mdc rules are copied; --check flags drift.
    text = read_text(rule["path"])
    parsed = parse_simple_frontmatter(text)
    body = (parsed[1] if parsed else text).strip("\n")
    rel = rule["path"].relative_to(root)
    return "\n".join([f"<!-- Copy of `{rel}` (canonical). {GENERATED_MARKER} -->", "", body]) + "\n"


def build_generated_claude_block(rules: list[dict[str, Any]], root: Path) -> str:
    always = sorted((r for r in rules if r["always_apply"]), key=lambda r: r["name"])
    read_when = sorted(
        (r for r in rules if not r["always_apply"] and not r["globs"] and r["description"]),
        key=lambda r: r["name"],
    )
    lines = [
        PARITY_START,
        "",
        "## Cursor to Claude Code (generated)",
        "",
        "| Cursor | Claude Code | Notes |",
        "|---|---|---|",
        "| `.cursor/mcp.json` | `.mcp.json` | `${env:VAR}` becomes `${VAR}`. Cursor `envFile` is dropped; export the vars. |",
        "| `.cursor/rules/*/RULE.md` (`alwaysApply: true`) | `@.cursor/rules/...` imports below | Canonical rules stay under `.cursor/rules/`. |",
        "| `.cursor/rules/*.mdc` (`alwaysApply: true`) | `.claude/rules/<name>.md` generated copies | Claude Code does not load `@` imports of `.mdc` files. Edit the `.mdc`, then rerun the generator. |",
        "| `.cursor/rules` with `globs:` | `.claude/rules/*.md` | Path-scoped pointers only. |",
        "| `.cursor/agents/*.md` | `.claude/agents/*.md` | Thin pointers; canonical playbooks stay in `.cursor/agents/`. |",
        "| `.cursor/skills/*/SKILL.md` | `.claude/skills/*/SKILL.md` | Thin pointers. |",
        "",
        "Does not transfer: Cursor marketplace plugins, canvases and Cursor OAuth sessions. Remote MCP servers need re-authorising in Claude Code (`/mcp`).",
        "",
    ]
    if always:
        lines += ["### Always-applied rules", ""]
        for r in always:
            rel = r["path"].relative_to(root)
            if is_mdc(r):
                lines.append(f"- `{rel}` (loaded from `.claude/rules/{r['name']}.md`)")
            else:
                lines.append(f"@{rel}")
        lines.append("")
    if read_when:
        lines += ["### Read when (agent-requestable)", "", "| When | Rule |", "|---|---|"]
        for r in read_when:
            desc = r["description"].replace("|", "\\|")
            lines.append(f"| {desc} | `{r['path'].relative_to(root)}` |")
        lines.append("")
    lines += [f"<!-- {GENERATED_MARKER} -->", PARITY_END]
    return "\n".join(lines) + "\n"


def default_claude_template(root: Path, cfg: Config) -> str:
    if cfg.claude_template:
        tpl = root / cfg.claude_template
        if tpl.is_file():
            return read_text(tpl)
    if (root / "AGENTS.md").is_file():
        return "@AGENTS.md\n\n"
    return "# Project instructions\n\n"


def expected_claude_md(root: Path, block: str, cfg: Config) -> str:
    path = root / "CLAUDE.md"
    if not path.is_file() or path.is_symlink():
        base = default_claude_template(root, cfg)
    else:
        base = read_text(path)
    if PARITY_START in base and PARITY_END in base:
        pre, rest = base.split(PARITY_START, 1)
        _, post = rest.split(PARITY_END, 1)
        out = pre.rstrip() + "\n\n" + block + post.lstrip("\n")
    else:
        out = base.rstrip() + "\n\n" + block
    return out if out.endswith("\n") else out + "\n"


def merge_claude_md(root: Path, block: str, check: bool, result: SyncResult, cfg: Config) -> None:
    path = root / "CLAUDE.md"
    if path.is_symlink():
        if check:
            result.drift.append("CLAUDE.md is a symlink")
            return
        path.unlink()
    expected = expected_claude_md(root, block, cfg)
    if check:
        if not path.is_file():
            result.drift.append("missing CLAUDE.md")
        elif read_text(path) != expected:
            result.drift.append("drift CLAUDE.md")
        return
    path.write_text(expected, encoding="utf-8")


# ---------------------------------------------------------------- agents, skills


def map_agent_model(raw: str | None) -> str | None:
    """Keep Claude Code aliases only; drop Cursor model slugs."""
    low = (raw or "").strip().lower()
    return low if low in CLAUDE_MODEL_ALIASES else None


def agent_is_valid(path: Path) -> bool:
    stem = path.stem.lower()
    if stem in AGENT_SKIP_NAMES or stem.endswith("-state"):
        return False
    fm = parse_simple_frontmatter(read_text(path))
    return fm is not None and "name" in fm[0]


def lane_owned(path: Path, cfg: Config) -> bool:
    if not cfg.lane_note:
        return False
    return not any(path.stem.startswith(p) for p in cfg.shared_agent_prefixes)


def lane_description(desc: str, cfg: Config) -> str:
    text = " ".join(desc.split())
    text = re.sub(r"\bUse (it )?proactively\b", "Runs", text, flags=re.I).strip()
    return f"{cfg.lane_note} {text}".strip()


def build_agent_pointer(path: Path, cfg: Config) -> str:
    text = read_text(path)
    fm, _ = parse_simple_frontmatter(text) or ({}, text)
    name = fm.get("name", path.stem)
    model = map_agent_model(fm.get("model"))
    fm_lines = extract_frontmatter_lines(text)
    out_fm = [f"name: {name}"]
    skip_keys = {"name", "model"}
    if lane_owned(path, cfg):
        skip_keys.add("description")
        out_fm.extend(yaml_description_lines(lane_description(fm.get("description", ""), cfg)))
    i = 0
    while i < len(fm_lines):
        line = fm_lines[i]
        m = re.match(r"^([A-Za-z0-9_-]+):", line)
        if m and m.group(1) in skip_keys:
            i += 1
            while i < len(fm_lines) and fm_lines[i].startswith(" "):
                i += 1
            continue
        out_fm.append(sanitize_prose(line))
        i += 1
    while out_fm and not out_fm[-1].strip():
        out_fm.pop()
    if model:
        out_fm.append(f"model: {model}")
    return "\n".join(
        [
            "---",
            *out_fm,
            "---",
            "",
            f"Canonical instructions: `.cursor/agents/{path.name}`. Read that file and follow it completely.",
            "",
            f"<!-- {GENERATED_MARKER} -->",
        ]
    ) + "\n"


def build_skill_pointer(path: Path, root: Path) -> str:
    fm, _ = parse_simple_frontmatter(read_text(path)) or ({}, "")
    lines = ["---", f"name: {fm.get('name', path.parent.name)}"]
    lines.extend(yaml_description_lines(fm.get("description", "")))
    lines += [
        "---",
        "",
        f"Read and follow `{path.relative_to(root)}` (canonical).",
        "",
        f"<!-- {GENERATED_MARKER} -->",
    ]
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------- hooks


def claude_hook_command(command: str, cfg: Config) -> str:
    cmd = command.strip()
    if any(h in cmd for h in cfg.claude_flag_hooks) and "--claude" not in cmd:
        return f"{cmd} --claude"
    return cmd


def claude_hook_matcher(event: str, entry: dict[str, Any], cfg: Config) -> str | None:
    if entry.get("matcher"):
        return str(entry["matcher"])
    if event == "PreToolUse":
        cmd = entry.get("command", "")
        for rule in cfg.hook_matchers:
            if rule.get("contains") and rule["contains"] in cmd:
                return rule.get("matcher")
    return None


def build_hooks_settings(
    root: Path, cfg: Config, existing: dict[str, Any] | None
) -> str | None:
    src = root / ".cursor" / "hooks.json"
    if not src.is_file():
        return None
    hooks_in = json.loads(read_text(src)).get("hooks") or {}
    hooks_out: dict[str, list[dict[str, Any]]] = {}
    for event, entries in hooks_in.items():
        claude_event = CURSOR_HOOK_TO_CLAUDE.get(event.lower())
        if not claude_event:
            continue
        groups = []
        for entry in entries:
            if not isinstance(entry, dict):
                continue
            cmd = entry.get("command", "")
            if any(s in cmd for s in cfg.skip_hooks):
                continue
            handler: dict[str, Any] = {
                "type": "command",
                "command": claude_hook_command(cmd, cfg),
            }
            if "timeout" in entry:
                handler["timeout"] = entry["timeout"]
            group: dict[str, Any] = {"hooks": [handler]}
            matcher = claude_hook_matcher(claude_event, entry, cfg)
            if matcher is not None:
                group["matcher"] = matcher
            groups.append(group)
        if groups:
            hooks_out[claude_event] = groups
    if not hooks_out:
        return None
    payload: dict[str, Any] = {"//generated": GENERATED_MARKER}
    # Keep hand-added top-level keys of an existing generated file.
    for key, value in (existing or {}).items():
        if key not in ("//generated", "hooks"):
            payload[key] = value
    payload["hooks"] = hooks_out
    return json.dumps(payload, indent=2) + "\n"


def append_gitignore(root: Path, check: bool, result: SyncResult, cfg: Config) -> None:
    gi = root / ".gitignore"
    existing = read_text(gi) if gi.is_file() else ""
    missing = [ln for ln in cfg.gitignore_lines if ln not in existing.splitlines()]
    if not missing:
        return
    if check:
        result.drift.append(f".gitignore missing: {', '.join(missing)}")
        return
    new = existing.rstrip() + "\n\n# Claude Code local overrides\n" + "\n".join(missing) + "\n"
    gi.write_text(new.lstrip("\n"), encoding="utf-8")


# ---------------------------------------------------------------- driver


def sync_repo(root: Path, check: bool, cfg: Config) -> SyncResult:
    result = SyncResult()
    rules = collect_cursor_rules(root / ".cursor" / "rules")

    mcp = build_mcp_json(root, result, cfg)
    if mcp is not None:
        write_or_check(root / ".mcp.json", mcp, check, result, root)

    merge_claude_md(root, build_generated_claude_block(rules, root), check, result, cfg)

    agents_dir = root / ".cursor" / "agents"
    if agents_dir.is_dir():
        for agent in sorted(agents_dir.glob("*.md")):
            if not agent_is_valid(agent):
                continue
            dest = root / ".claude" / "agents" / agent.name
            if dest.is_file() and not is_generated(read_text(dest)):
                result.conflicts.append(f"{dest.relative_to(root)}: hand-written Claude agent skipped")
                continue
            write_or_check(dest, build_agent_pointer(agent, cfg), check, result, root)

    skills_dir = root / ".cursor" / "skills"
    if skills_dir.is_dir():
        for skill in sorted(skills_dir.glob("*/SKILL.md")):
            dest = root / ".claude" / "skills" / skill.parent.name / "SKILL.md"
            if dest.is_file() and not is_generated(read_text(dest)):
                result.notes.append(f"kept hand-written skill {dest.relative_to(root)}")
                continue
            write_or_check(dest, build_skill_pointer(skill, root), check, result, root)

    for rule in rules:
        dest = root / ".claude" / "rules" / f"{rule['name']}.md"
        if rule["always_apply"]:
            if not is_mdc(rule):
                continue
            content = build_always_rule_copy(rule, root)
        elif rule["globs"]:
            content = build_glob_rule(rule, root)
        else:
            continue
        write_or_check(dest, content, check, result, root)

    settings = root / ".claude" / "settings.json"
    if settings.is_file() and not is_generated(read_text(settings)):
        result.notes.append("kept hand-written .claude/settings.json; Cursor hooks not ported")
    else:
        existing = None
        if settings.is_file():
            try:
                existing = json.loads(read_text(settings))
            except json.JSONDecodeError:
                existing = None
        hooks_json = build_hooks_settings(root, cfg, existing)
        if hooks_json:
            write_or_check(settings, hooks_json, check, result, root)

    append_gitignore(root, check, result, cfg)
    return result


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Generate Claude Code config from .cursor/")
    p.add_argument("repo", help="path to the repo root")
    p.add_argument("--check", action="store_true", help="report drift only; exit 1 if anything differs")
    p.add_argument("--config", help=f"JSON config file (default: <repo>/{DEFAULT_CONFIG_NAME} if present)")
    p.add_argument("--allow-no-rules", action="store_true", help="run even when .cursor/rules/ is empty")
    p.add_argument("--env-default", action="append", default=[], metavar="NAME=VALUE",
                   help="public default for ${env:NAME} (repeatable)")
    p.add_argument("--lane-note", help="sentence prefixed to agent descriptions")
    p.add_argument("--shared-agent-prefix", action="append", default=[],
                   help="agents with this name prefix get no lane note (repeatable)")
    p.add_argument("--flag-hook", action="append", default=[],
                   help="append --claude to hook commands containing this text (repeatable)")
    p.add_argument("--skip-hook", action="append", default=[],
                   help="do not port hook commands containing this text (repeatable)")
    p.add_argument("--claude-template", help="CLAUDE.md template path, relative to the repo")
    args = p.parse_args(argv)

    root = repo_root(args.repo)
    cfg = load_config(root, args.config)
    for item in args.env_default:
        if "=" not in item:
            sys.stderr.write(f"--env-default needs NAME=VALUE, got {item!r}\n")
            return 2
        k, v = item.split("=", 1)
        cfg.env_defaults[k] = v
    if args.lane_note:
        cfg.lane_note = args.lane_note
    cfg.shared_agent_prefixes += args.shared_agent_prefix
    cfg.claude_flag_hooks += args.flag_hook
    cfg.skip_hooks += args.skip_hook
    if args.claude_template:
        cfg.claude_template = args.claude_template

    rules_dir = root / ".cursor" / "rules"
    has_rules = rules_dir.is_dir() and (
        any(rules_dir.glob("*.mdc")) or any(rules_dir.glob("*/RULE.md"))
    )
    if not has_rules and not args.allow_no_rules:
        sys.stderr.write(
            f"No Cursor rules in {root} (.cursor/rules/ is missing or empty).\n"
            "Add at least one rule first, or pass --allow-no-rules.\n"
        )
        return 3

    result = sync_repo(root, args.check, cfg)
    if result.envfile_dropped:
        print("envFile dropped for MCP servers: " + ", ".join(sorted(result.envfile_dropped)))
    for note in result.notes:
        print(f"note: {note}")
    for c in result.conflicts:
        print(f"conflict: {c}", file=sys.stderr)
    for d in result.drift:
        print(f"drift: {d}", file=sys.stderr)
    if args.check:
        if result.drift or result.conflicts:
            return 1
        print("in sync")
        return 0
    return 1 if result.conflicts else 0


if __name__ == "__main__":
    sys.exit(main())
